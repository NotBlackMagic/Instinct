#include "usbDevice.hpp"

#include "tx_api.h"

class OpticalFlowThread {
	public:
		/// @brief Real-time performance, execution latency, and health statistics
		struct Statistics {
			// Rates (Updated every second)
			float camFPS = 0.0f;		///< DCMI frame rate (target: 30 FPS)
			float tofFPS = 0.0f;		///< VL53L8CH ODR (target: 15 Hz)

			// Pipeline & Quality Health
			uint32_t frameCount = 0;	///< Total frames captured
			uint32_t frameDrops = 0;	///< DCMI errors or pipeline restarts
			uint32_t flowDrops = 0;		///< Frames with invalid flow output
			float lastQuality = 0.0f;	///< Latest optical flow confidence (0.0 to 1.0)

			// Algorithm Execution Times
			uint32_t procTime = 0;		///< Last flow execution latency
			uint32_t maxProcTime = 0;	///< Peak latency (detects MVE jitter / stalls)

			// Downward Range
			uint32_t tofSamples = 0;	///< Total range read cycles
			uint32_t tofDrops = 0;		///< Samples with no valid center targets
		};

		static void Init();

		/// @brief Returns Optical Flow performance statistics.
		static Statistics GetStatistics() { return stats; }

		/// @brief Resets Optical Flow statistics counters.
		static void ResetStatistics() {
			stats = {};
		}

	private:
		static TX_THREAD threadPtr;
		static const uint16_t threadStackSize = 4096;
		__attribute__((aligned(32))) static uint8_t threadStack[threadStackSize];

		static Statistics stats;

		// Topic Instance IDs
		// Virtual sensor generated by the sensor hub are instance 255
		static constexpr uint8_t virtualInstanceID = 255;

		// Subscriber Topic Pointers
		static Topic<IMUMsg>* topicVirtualIMU;

		// Sensor publishers
		static Topic<FlowMsg> topicFlow;
		static Topic<RangeMsg> topicRange;

		// The Core Math Engine
		static OpticalFlow flow;

		// Synchronization
		static TX_EVENT_FLAGS_GROUP event;

		// Event Flags Definitions
		static constexpr ULONG EVT_TOF_DRDY = 0x01;
		static constexpr ULONG EVT_DCMI_FRAME = 0x02;
		static constexpr ULONG EVT_DCMI_ERR = 0x04;

		static void Run(ULONG input);

		static void ToFIntCallback(void* ctx, EXTIManager::Edge edge);
		static void DCMIFrameCallback(void* ctx, CameraDCMI::Event evt);
};